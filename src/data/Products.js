// --- Funciones del Carrito con LocalStorage ---
export function obtenerCarrito() {
  const guardado = localStorage.getItem('carritoTaberna');
  return guardado ? JSON.parse(guardado) : [];
}

export function guardarCarrito(carrito) {
  localStorage.setItem('carritoTaberna', JSON.stringify(carrito));
}

export function agregarAlCarrito(producto, cantidad = 1) {
  const carrito = obtenerCarrito();
  const unitario = precioFinal(producto);
  const existe = carrito.find((item) => item.id === producto.id);

  let nuevoCarrito;
  if (existe) {
    nuevoCarrito = carrito.map((item) =>
      item.id === producto.id ? { ...item, cantidad: item.cantidad + cantidad } : item
    );
  } else {
    nuevoCarrito = [
      ...carrito,
      {
        id: producto.id,
        nombre: producto.nombre,
        imagen: producto.imagen,
        precio: producto.precio,
        precioFinal: unitario,
        cantidad: cantidad,
      },
    ];
  }
  guardarCarrito(nuevoCarrito);
  return nuevoCarrito;
}

export function eliminarDelCarrito(id) {
  const carrito = obtenerCarrito().filter((item) => item.id !== id);
  guardarCarrito(carrito);
  return carrito;
}

export function vaciarCarrito() {
  localStorage.removeItem('carritoTaberna');
  return [];
}

export function contarItems() {
  return obtenerCarrito().reduce((suma, item) => suma + item.cantidad, 0);
}

export function totalCarrito(sesion = null) {
  return obtenerCarrito().reduce(
    (suma, item) => suma + precioSocio(item.precioFinal, sesion, item.id) * item.cantidad,
    0
  );
}

