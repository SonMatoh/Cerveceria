export function obtenerUsuarios() {
  let guardados = [];
  try {
    const dato = JSON.parse(localStorage.getItem('usuariosTaberna'));
    if (Array.isArray(dato)) {
      guardados = dato;
    }
  } catch {
    guardados = [];
  }
  const correosGuardados = guardados.map((u) => String(u.email || '').toLowerCase());
  const faltantes = usuariosIniciales.filter(
    (u) => !correosGuardados.includes(u.email.toLowerCase())
  );

  const listaCompleta = [...faltantes, ...guardados];
  localStorage.setItem('usuariosTaberna', JSON.stringify(listaCompleta));
  return listaCompleta;
}

export function restaurarUsuarios() {
  localStorage.setItem('usuariosTaberna', JSON.stringify(usuariosIniciales));
  return usuariosIniciales;
}

export function autenticar(email, password) {
  const correo = String(email || '').trim().toLowerCase();
  const usuarios = obtenerUsuarios();
  return (
    usuarios.find((u) => u.email.toLowerCase() === correo && u.password === password) ||
    null
  );
}

export function esAdmin(email) {
  const correo = String(email || '').trim().toLowerCase();
  const usuarios = obtenerUsuarios();
  return usuarios.some((u) => u.email.toLowerCase() === correo && u.rol === 'admin');
}

export function registrarUsuario({ nombre, email, password, fechaNacimiento = '' }) {
  const correo = String(email || '').trim().toLowerCase();
  const usuarios = obtenerUsuarios();
  if (usuarios.some((u) => u.email.toLowerCase() === correo)) {
    return { ok: false };
  }
  const nuevo = {
    nombre: String(nombre || '').trim(),
    email: correo,
    password: String(password || ''),
    fechaNacimiento,
    rol: 'cliente',
  };
  const actualizados = [...usuarios, nuevo];
  localStorage.setItem('usuariosTaberna', JSON.stringify(actualizados));
  return { ok: true };
}

