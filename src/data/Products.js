// --- Funciones de Utilidad y Formato ---
export function formatoClp(valor) {
  return '$' + Number(valor || 0).toLocaleString('es-CL');
}

export function precioFinal(producto) {
  const descuento = Number(producto?.descuento) || 0;
  const precio = Number(producto?.precio) || 0;
  if (descuento > 0) {
    return Math.round(precio * (1 - descuento / 100));
  }
  return precio;
}

export function esElegido(sesion, productoId) {
  if (!sesion) return false;
  const productos = obtenerProductos();
  const elegidos = productos.slice(0, 3);
  return elegidos.some((p) => Number(p.id) === Number(productoId));
}

export function precioSocio(precio, sesion, productoId) {
  const valor = Number(precio) || 0;
  if (!esElegido(sesion, productoId)) return valor;
  return Math.round(valor * 0.9);
}

