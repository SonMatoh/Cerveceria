-- V1: esquema inicial de La Taberna de Snorlax.
-- Generado a partir de la base Neon el 2026-11-26.
-- Un clon desde cero queda identico ejecutando V1 + V2.

create table regiones (
    id bigint generated by default as identity primary key,
    nombre varchar(100) not null,
    constraint uq_regiones_nombre unique (nombre)
);

create table comunas (
    id bigint generated by default as identity primary key,
    nombre varchar(100) not null,
    region_id bigint not null,
    constraint fk_comunas_region foreign key (region_id) references regiones (id),
    constraint uq_comunas_region_nombre unique (region_id, nombre)
);

create table direcciones (
    id bigint generated by default as identity primary key,
    calle varchar(150) not null,
    numero varchar(30),
    complemento varchar(100),
    comuna_id bigint not null,
    constraint fk_direcciones_comuna foreign key (comuna_id) references comunas (id)
);

create table categorias (
    id bigint generated by default as identity primary key,
    nombre varchar(100) not null,
    constraint uq_categorias_nombre unique (nombre)
);

create table usuarios (
    id bigint generated by default as identity primary key,
    nombre varchar(100) not null,
    email varchar(255) not null,
    password varchar(255) not null,
    rol varchar(255) not null,
    fecha_nacimiento date,
    direccion_id bigint,
    constraint uq_usuarios_email unique (email),
    constraint fk_usuarios_direccion foreign key (direccion_id) references direcciones (id)
);

create table productos (
    id bigint generated by default as identity primary key,
    nombre varchar(255) not null,
    estilo varchar(255),
    descripcion text,
    precio integer not null,
    imagen_url varchar(255),
    categoria varchar(255) not null,
    descuento integer not null,
    categoria_id bigint,
    stock integer not null default 0,
    constraint fk_productos_categoria foreign key (categoria_id) references categorias (id),
    constraint ck_productos_stock check (stock >= 0)
);

create table ordenes (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null,
    nro_orden varchar(20) not null,
    subtotal integer not null default 0,
    descuento integer not null default 0,
    total integer not null,
    estado varchar(255) not null,
    fecha timestamp not null,
    metodo_pago varchar(30),
    entrega varchar(30),
    calle varchar(150),
    numero varchar(30),
    complemento varchar(100),
    comuna varchar(100),
    region varchar(100),
    constraint uq_ordenes_nro_orden unique (nro_orden),
    constraint fk_ordenes_usuario foreign key (usuario_id) references usuarios (id)
);

create table detalle_ordenes (
    id bigint generated by default as identity primary key,
    orden_id bigint not null,
    producto_id bigint not null,
    cantidad integer not null,
    precio_unitario integer not null,
    constraint fk_detalle_ordenes_orden foreign key (orden_id) references ordenes (id),
    constraint fk_detalle_ordenes_producto foreign key (producto_id) references productos (id),
    constraint uq_detalle_orden_producto unique (orden_id, producto_id)
);

create table imagenes (
    id bigint generated by default as identity primary key,
    url varchar(500) not null,
    producto_id bigint not null,
    constraint fk_imagenes_producto foreign key (producto_id) references productos (id)
);

create table blogs (
    id bigint generated by default as identity primary key,
    titulo varchar(255) not null,
    fecha varchar(255),
    autor varchar(255),
    imagen_url varchar(255),
    resumen text,
    contenido text
);

create index idx_ordenes_usuario on ordenes (usuario_id);
create index idx_ordenes_fecha on ordenes (fecha);
create index idx_productos_categoria on productos (categoria);
create index idx_productos_nombre on productos (nombre);

-- Respaldo de generacion del codigo de orden.
-- El servicio tambien puede generarlo; esto cubre inserts directos o antiguos.
create or replace function set_nro_orden() returns trigger as $$
begin
    if new.nro_orden is null then
        new.nro_orden := 'ORDER-' || lpad(new.id::text, 6, '0');
    end if;
    return new;
end;
$$ language plpgsql;

create trigger trg_set_nro_orden
before insert on ordenes
for each row execute function set_nro_orden();
